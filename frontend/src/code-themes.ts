/**
 * Monaco 编辑器配色数据（纯数据，不引 monaco）：base + colors + token rules。
 *
 * 约定：
 * - `foreground` 不带 `#`（Monaco 的 ITokenThemeRule 口径）；
 * - token 名按 Monaco 各语言 Monarch 的通用命名给（comment / keyword / string / number /
 *   type / function / variable / attribute / tag / operator / regexp …），一个主题一套，
 *   不逐语言分支 —— 阅读器只求一眼能分出结构与字面量；
 * - 语义三档（本项目 / 局部 / 外部）不在这里，它们是 Monaco decoration 的 CSS 类，
 *   颜色由 styles.css 的 `--hl-*` 决定，所以换主题时自动跟随。
 *
 * 出处（仅借用配色值，未复制主题代码）：
 * One Dark / One Light — atom/one-dark-syntax、one-light-syntax（MIT，GitHub Inc.）；
 * Darcula — IntelliJ IDEA 内置主题；Material Palenight — material-theme（MIT）；
 * Nord — nordtheme/nord（MIT）；Catppuccin Mocha — catppuccin（MIT）。
 */
import type { ThemeId } from './themes';

export interface TokenRule {
  token: string;
  foreground?: string;
  background?: string;
  fontStyle?: string;
}

export interface CodeTheme {
  base: 'vs' | 'vs-dark';
  colors: Record<string, string>;
  rules: TokenRule[];
}

/** 编辑器骨架色（各主题只填差异项，未填的沿用 base 默认）。 */
function skin(bg: string, fg: string, opts: Partial<Record<string, string>> = {}): Record<string, string> {
  return {
    'editor.background': bg,
    'editor.foreground': fg,
    'editorGutter.background': bg,
    'minimap.background': bg,
    'editorWidget.background': opts.widget ?? bg,
    'editorWidget.border': opts.widgetBorder ?? opts.line ?? bg,
    'editor.lineHighlightBackground': opts.line ?? bg,
    'editor.selectionBackground': opts.selection ?? bg,
    'editor.selectionHighlightBackground': opts.selectionSoft ?? opts.selection ?? bg,
    'editorLineNumber.foreground': opts.lineNumber ?? fg,
    'editorLineNumber.activeForeground': opts.lineNumberActive ?? fg,
    'editorCursor.foreground': opts.cursor ?? fg,
    'editorIndentGuide.background1': opts.indent ?? opts.line ?? bg,
    'editorIndentGuide.activeBackground1': opts.indentActive ?? opts.lineNumber ?? fg,
    'editorWhitespace.foreground': opts.whitespace ?? opts.indent ?? opts.line ?? bg,
    'editorBracketMatch.background': opts.bracket ?? opts.selection ?? bg,
    'editorBracketMatch.border': opts.bracketBorder ?? opts.line ?? fg,
    'editorFindMatchBackground': opts.find ?? opts.selection ?? bg,
    'editorFindMatchHighlightBackground': opts.findSoft ?? opts.selectionSoft ?? bg,
  };
}

